// Aligned tables, like Prettier writes them: wide characters count twice.
const width = (s: string) =>
  [...s.normalize("NFC")].reduce(
    (w, c) => w + (/\p{M}/u.test(c) ? 0 : /[\u1100-\u115F\u2E80-\uA4CF\uAC00-\uD7A3\uF900-\uFAFF\uFF00-\uFF60]/u.test(c) ? 2 : 1),
    0,
  );
function table(head: string[], rows: string[][]) {
  const widths = head.map((h, i) => Math.max(3, width(h), ...rows.map((r) => width(r[i]!))));
  const line = (cells: string[]) => `| ${cells.map((c, i) => c + " ".repeat(widths[i]! - width(c))).join(" | ")} |`;
  return [line(head), `| ${widths.map((w) => "-".repeat(w)).join(" | ")} |`, ...rows.map(line)];
}

const code = (s: string) => "`" + s.replace(/\|/g, "\\|") + "`";

function section(period: Period) {
  const [first, second] = DAYS.map((d) => period.at(moment(d, "YYYY-MM-DD"), ctx));
  const out: string[] = [`### ${period.name}`, ""];
  out.push(`${period.span}.${period.clock ? ` Dated in ${period.clock}.` : ""} Command: **${period.command ?? `Open this ${period.name.toLowerCase()}`}**.`, "");
  if (period.dates?.length) {
    out.push(`Settings: ${period.dates.map((d) => `**${d.name}**, ${code(d.default)} by default`).join("; ")}.`, "");
  }

  const examples = period.examples.map((format) => [
    `${code(format)}${format === period.format ? " (default)" : ""}`,
    ...[first!, second!].map((i) => code(render(format, period, i).text)),
  ]);
  out.push(...table(["Example", ...DAYS.map(heading)], examples), "");

  const rows = reference(period, first!).map((row) => [
    code(row.token),
    row.desc.replace(/\{\{[^}]+\}\}/g, (t) => code(t)),
    row.value ? code(row.value) : "nothing",
  ]);
  out.push(...table(["Token", "Means", heading(DAYS[0]!)], rows), "");

  if (SOURCES[period.key]) out.push(SOURCES[period.key]!, "");
  return out.join("\n");
}

